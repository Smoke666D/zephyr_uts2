/**
 *  @brief Перечисление поддерживаемых типов системных очередей задач (воркеров)
 */
typedef enum worker_type
{
    COMMON_WORKER,    ///< Стандартная очередь задач общего назначения
    REAL_TIME_WORKER  ///< Высокоприоритетная очередь задач реального времени
} worker_type_t;

// Псевдоним для обратной совместимости с legacy-кодом проекта
typedef worker_type_t worker_type;

/***************************************************************************************************
 *                                         GLOBAL VARIABLES
 **************************************************************************************************/

/***************************************************************************************************
 *                                    PUBLIC FUNCTION PROTOTYPES
 **************************************************************************************************/

/// @brief Отправка задачи в очередь
void app_worker_submit(struct k_work *_work, worker_type_t _worker_type);

/// @brief Повторная отправка отложенной задачи в очередь
void app_worker_reschedule_submit(struct k_work_delayable *_delayed_work, 
                                  k_timeout_t _delay, 
                                  worker_type_t _worker_type);

/// @brief Отправка поллинг-задачи в очередь
void app_worker_poll_submit(struct k_work_poll *_work, 
                            struct k_poll_event *_poll_event, 
                            worker_type_t _worker_type);

